#!/usr/bin/env python3
"""Repository lint for the skills marketplace.

Checks skill frontmatter, skill layout, plugin manifests, evals and the
public-safety rules in CONTRIBUTING.md. Python standard library only.

Findings print as `path:line: error|warning ID message`. The exit code is 1
when there is at least one error (or a warning under --strict), else 0.
"""

from __future__ import annotations

import argparse
import ipaddress
import json
import os
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

MARKETPLACE = "rene-roscher-skills"
PORTABLE_PLUGINS = {"core", "saas"}
NO_SKILL_PLUGINS = {"docs-tools", "guardrails"}
# Plugins allowed to ship hooks/ (and only hooks): each hook script must pass its --self-test.
HOOK_PLUGINS = {"guardrails"}
SPEC_KEYS = ["name", "description", "license", "compatibility", "metadata", "allowed-tools"]
LISTING_WARN = 500  # L21: listing text above this many characters is a warning
CLAUDE_KEYS = ["paths", "when_to_use", "disable-model-invocation", "user-invocable"]
EVAL_KINDS = {"trigger", "near-miss", "output", "adversarial"}
NAME_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
SEMVER_RE = re.compile(r"^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$")

# Inline allow: <!-- lint-allow: L13 reason --> on the same or the previous line.
ALLOW_RE = re.compile(r"lint-allow:\s*(L\d{2})\s+\S")
ALLOWABLE_IN_PLUGINS = {"L09", "L10", "L11", "L13"}

SKIP_DIRS = {".git", "node_modules", "__pycache__", ".venv", "eval-out", "results"}
SKIP_FILES = {".denylist.local"}
# Files whose job is to name the patterns: content checks other than the
# private-term check skip them.
SELF_FILES = {"tools/lint.py"}
VERBATIM_FILES = {"LICENSE"}

ABS_PATH_RE = re.compile(r"(?:^|[\s\"'(`=])(/home/|/Users/)|\b[A-Za-z]:\\(?=[A-Za-z0-9_.])")
PIPE_SHELL_RES = [
    re.compile(r"\b(curl|wget)\b[^\n|]*\|\s*(sudo\s+)?(ba|z|da|k)?sh\b"),
    re.compile(r"\b(iwr|irm|Invoke-WebRequest|Invoke-RestMethod)\b[^\n|]*\|\s*iex\b", re.I),
    re.compile(r"\b(ba)?sh\s+<\(\s*(curl|wget)\b"),
]
REMOTE_INSTR_RES = [
    re.compile(r"\b(fetch|load|read|download)\b[^.\n]{0,60}\b(instructions?|prompts?|rules)\b[^.\n]{0,60}https?://", re.I),
    re.compile(r"https?://\S+[^.\n]{0,40}\b(and|then)\s+(follow|obey|execute|apply)\b", re.I),
    re.compile(r"(?:^|\s)@https?://"),
]
DYNAMIC_CTX_RE = re.compile(r"!`[^`\n]+`")
IPV4_RE = re.compile(r"(?<![\w.])(?:25[0-5]|2[0-4]\d|1?\d?\d)(?:\.(?:25[0-5]|2[0-4]\d|1?\d?\d)){3}(?![\w.]*\d)")
IPV6_RE = re.compile(
    r"(?<![\w:.])(?=[0-9a-f:]*\d)(?:(?:[0-9a-f]{1,4}:){4,7}[0-9a-f]{1,4}"
    r"|(?:[0-9a-f]{1,4}:){0,6}(?:[0-9a-f]{1,4})?::(?:[0-9a-f]{1,4}(?::[0-9a-f]{1,4}){0,6})?)"
    r"(?![\w:(])",
    re.I,
)
EMAIL_RE = re.compile(r"[A-Za-z0-9._%+-]+@([A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,})\b")
EMAIL_OK_RE = re.compile(r"^(?:[A-Za-z0-9-]+\.)*example\.(?:com|org|net)$", re.I)
HEX40_RE = re.compile(r"(?<![0-9A-Za-z])[0-9a-f]{40}(?![0-9A-Za-z])")
HEX_WORDS = {"ed25519"}
SHORT_HASH_RE = re.compile(r"(?<![0-9A-Za-z#])(?=[0-9a-f]*[a-f])(?=[0-9a-f]*\d)[0-9a-f]{7,39}(?![0-9A-Za-z])")
ATTRIB_HARD_RES = [
    re.compile(r"co-authored-by", re.I),
    re.compile(r"Generated with\W{0,3}(?:\[|Claude|ChatGPT|Copilot|Cursor|Codex|Gemini|an? AI\b|AI\b|LLM)"),
    re.compile(r"generated by (?:an? )?(?:AI|Claude|ChatGPT|Copilot|LLM)\b", re.I),
    re.compile("\U0001F916"),
]
ATTRIB_SOFT_RE = re.compile(r"\bGenerated with\b")
UNSOURCED_HARD_RE = re.compile(r"\bCVE-\d{4}-\d{4,}\b")
UNSOURCED_SOFT_RE = re.compile(r"\b(known (?:issue|bug)|upstream (?:issue|bug)|regression in|fixed in)\b|(?<![\w&/])#\d{2,5}\b", re.I)
SLOP_RE = re.compile(
    r"\b(comprehensive|robust(?:ly|ness)?|seamless(?:ly)?|leverag(?:e|es|ed|ing)|delv(?:e|es|ing)|crucial(?:ly)?"
    r"|elevat(?:e|es|ing)|streamlin(?:e|es|ed|ing)|cutting-edge|game-?changer|in today's|empower(?:s|ing)?"
    r"|unlock(?:s|ing)? the|harness(?:es|ing)? the power|supercharg(?:e|es|ed|ing)|effortless(?:ly)?)\b",
    re.I,
)
PLACEHOLDER_RE = re.compile(r"<Rule\b|<URL>|<one line>|<what you give up>|<reproducible recipe")
BUILD_MARKER_RE = re.compile(r"VERIFY AT BUILD")
LINK_RE = re.compile(r"!?\[[^\]]*\]\(\s*<?([^)\s>]+)>?(?:\s+\"[^\"]*\")?\s*\)")

DOC_V4 = [ipaddress.ip_network(n) for n in ("192.0.2.0/24", "198.51.100.0/24", "203.0.113.0/24", "127.0.0.0/8", "0.0.0.0/32")]
DOC_V6 = [ipaddress.ip_network(n) for n in ("2001:db8::/32", "::1/128", "::/128")]


@dataclass
class Finding:
    path: str
    line: int
    level: str
    rule: str
    message: str


class Linter:
    def __init__(self, root: Path, strict: bool) -> None:
        self.root = root
        self.strict = strict
        self.findings: list[Finding] = []
        self.skill_names: set[str] = set()

    # -- reporting -------------------------------------------------------
    def rel(self, path: Path) -> str:
        try:
            return path.relative_to(self.root).as_posix()
        except ValueError:
            return path.as_posix()

    def add(self, path: Path | str, line: int, level: str, rule: str, message: str) -> None:
        p = path if isinstance(path, str) else self.rel(path)
        self.findings.append(Finding(p, line, level, rule, message))

    def err(self, path, line, rule, message):
        self.add(path, line, "error", rule, message)

    def warn(self, path, line, rule, message):
        self.add(path, line, "warning", rule, message)

    # -- file discovery --------------------------------------------------
    def files(self) -> list[Path]:
        try:
            out = subprocess.run(
                ["git", "-C", str(self.root), "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
                capture_output=True, check=True,
            ).stdout.decode()
            paths = [self.root / p for p in out.split("\0") if p]
            if paths:
                return sorted(p for p in paths if p.is_file() and p.name not in SKIP_FILES)
        except (OSError, subprocess.CalledProcessError):
            pass
        found = []
        for dirpath, dirnames, filenames in os.walk(self.root):
            dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
            for name in filenames:
                if name not in SKIP_FILES:
                    found.append(Path(dirpath) / name)
        return sorted(found)

    @staticmethod
    def read_text(path: Path) -> str | None:
        try:
            data = path.read_bytes()
        except OSError:
            return None
        if b"\0" in data[:8192]:
            return None
        try:
            return data.decode("utf-8")
        except UnicodeDecodeError:
            return None

    # -- content checks (every text file) --------------------------------
    def allowed(self, lines: list[str], idx: int, rule: str, in_plugins: bool) -> bool:
        if in_plugins and rule not in ALLOWABLE_IN_PLUGINS:
            return False
        for j in (idx, idx - 1):
            if 0 <= j < len(lines):
                for m in ALLOW_RE.finditer(lines[j]):
                    if m.group(1) == rule:
                        return True
        return False

    def check_content(self, path: Path, text: str, denylist: list[str]) -> None:
        rel = self.rel(path)
        lines = text.splitlines()
        in_plugins = rel.startswith("plugins/")
        in_workflows = rel.startswith(".github/workflows/")
        is_self = rel in SELF_FILES
        is_verbatim = rel in VERBATIM_FILES

        for i, line in enumerate(lines):
            n = i + 1

            for k, term in enumerate(denylist):
                if re.search(r"(?<![A-Za-z0-9])" + re.escape(term) + r"(?![A-Za-z0-9])", line, re.I):
                    # Never print the term: CI logs are public.
                    self.err(rel, n, "L14", f"private term #{k + 1} from the denylist")

            if is_self or is_verbatim:
                continue

            def hit(rule: str, message: str, level: str = "error") -> None:
                if self.allowed(lines, i, rule, in_plugins):
                    return
                self.add(rel, n, level, rule, message)

            if ABS_PATH_RE.search(line):
                hit("L09", "absolute or personal path (/home/, /Users/, drive letter)")
            for rx in PIPE_SHELL_RES:
                if rx.search(line):
                    hit("L10", "download piped into a shell")
                    break
            for rx in REMOTE_INSTR_RES:
                if rx.search(line):
                    hit("L11", "instructions fetched from a remote URL")
                    break
            if in_plugins and DYNAMIC_CTX_RE.search(line):
                hit("L11", "dynamic-context block (!`command`) runs a command at load time")

            for m in IPV4_RE.finditer(line):
                try:
                    ip = ipaddress.ip_address(m.group(0))
                except ValueError:
                    continue
                if not any(ip in net for net in DOC_V4):
                    hit("L13", f"IPv4 literal {m.group(0)} outside the documentation ranges")
            for m in IPV6_RE.finditer(line):
                cand = m.group(0)
                try:
                    ip = ipaddress.ip_address(cand)
                except ValueError:
                    continue
                if not any(ip in net for net in DOC_V6):
                    hit("L13", f"IPv6 literal {cand} outside 2001:db8::/32")
            for m in EMAIL_RE.finditer(line):
                full = m.group(0)
                if EMAIL_OK_RE.match(m.group(1)) or full.lower() == "git@github.com":
                    continue
                hit("L13", "email address outside example.com/.org/.net")
            if not in_workflows and rel != ".gitleaksignore":
                if HEX40_RE.search(line):
                    hit("L13", "40-character hex string (commit hash) outside .github/workflows")
                elif any(m.group(0) not in HEX_WORDS for m in SHORT_HASH_RE.finditer(line)):
                    hit("L13", "hex string that looks like a short commit hash", "warning")

            for rx in ATTRIB_HARD_RES:
                if rx.search(line):
                    hit("L17", "AI attribution or co-author trailer")
                    break
            else:
                if ATTRIB_SOFT_RE.search(line):
                    hit("L17", "'Generated with' reads like an attribution footer; rephrase", "warning")

            if UNSOURCED_HARD_RE.search(line) and "https://" not in line:
                hit("L15", "CVE identifier without a source URL on the same line")
            elif in_plugins and UNSOURCED_SOFT_RE.search(line) and "https://" not in line:
                hit("L15", "issue reference or 'known issue' claim without a source URL on the same line", "warning")

            if path.suffix.lower() in {".md", ".txt", ""} and not in_workflows:
                for m in SLOP_RE.finditer(line):
                    hit("W01", f"filler word '{m.group(0)}'", "warning")

            if in_plugins:
                if BUILD_MARKER_RE.search(line):
                    hit("L16", "build marker left in published text")
                if path.name == "SKILL.md" or "/references/" in rel:
                    if PLACEHOLDER_RE.search(line):
                        hit("L16", "template placeholder left in skill text")
                if re.search(r"\[opinion\]", line, re.I):
                    hit("L08", "[opinion] content belongs in templates/project-overlay/profiles/")

    # -- frontmatter -----------------------------------------------------
    def parse_frontmatter(self, path: Path, lines: list[str]):
        rel = self.rel(path)
        if not lines or lines[0].rstrip() != "---":
            self.err(rel, 1, "L01", "frontmatter must start on line 1 with ---")
            return None, 0
        end = None
        for i in range(1, len(lines)):
            if lines[i].rstrip() == "---":
                end = i
                break
        if end is None:
            self.err(rel, 1, "L01", "frontmatter has no closing ---")
            return None, 0

        data: dict[str, object] = {}
        order: list[tuple[str, int]] = []
        current = None
        for i in range(1, end):
            raw = lines[i]
            n = i + 1
            if not raw.strip() or raw.lstrip().startswith("#"):
                continue
            if "\t" in raw[: len(raw) - len(raw.lstrip())]:
                self.err(rel, n, "L01", "tab indentation in frontmatter")
                continue
            if not raw.startswith((" ", "-")):
                m = re.match(r"^([A-Za-z0-9_-]+):(?:\s+(.*))?$", raw.rstrip())
                if not m:
                    self.err(rel, n, "L01", "frontmatter line is not 'key: value'")
                    current = None
                    continue
                key, val = m.group(1), (m.group(2) or "").strip()
                if key in data:
                    self.err(rel, n, "L01", f"duplicate key '{key}'")
                order.append((key, n))
                if val == "":
                    data[key] = None
                    current = key
                    continue
                current = None
                if val[0] in "[{":
                    self.err(rel, n, "L01", f"flow-style value for '{key}'; use block style")
                    data[key] = val
                    continue
                if val in {"|", ">", "|-", ">-", "|+", ">+"}:
                    self.err(rel, n, "L01", f"multi-line scalar for '{key}'; use one quoted line")
                    data[key] = ""
                    continue
                data[key] = self.unquote(rel, n, val)
                continue
            # indented continuation of a block value
            if current is None:
                self.err(rel, n, "L01", "indented line without a parent key")
                continue
            s = raw.strip()
            if s.startswith("- "):
                if data[current] is None:
                    data[current] = []
                if not isinstance(data[current], list):
                    self.err(rel, n, "L01", f"'{current}' mixes list and mapping")
                    continue
                item = s[2:].strip()
                if item[:1] in "[{":
                    self.err(rel, n, "L01", "flow-style list item; use block style")
                data[current].append(self.unquote(rel, n, item))
            else:
                m = re.match(r"^([A-Za-z0-9_.-]+):\s*(.*)$", s)
                if not m:
                    self.err(rel, n, "L01", "frontmatter line is not 'key: value'")
                    continue
                if data[current] is None:
                    data[current] = {}
                if not isinstance(data[current], dict):
                    self.err(rel, n, "L01", f"'{current}' mixes list and mapping")
                    continue
                sub = m.group(2).strip()
                if sub == "" or sub[0] in "[{|>":
                    self.err(rel, n, "L01", f"'{current}.{m.group(1)}' must be a plain string value")
                data[current][m.group(1)] = self.unquote(rel, n, sub)
        return {"data": data, "order": order}, end + 1

    def unquote(self, rel: str, n: int, val: str) -> str:
        if len(val) >= 2 and val[0] == val[-1] and val[0] in "\"'":
            inner = val[1:-1]
            return inner.replace('\\"', '"') if val[0] == '"' else inner.replace("''", "'")
        if val[:1] in "\"'":
            self.err(rel, n, "L01", "unterminated quoted value")
        elif re.search(r":\s", val) or val.startswith(("&", "*", "!", "%", "@", "`")):
            self.err(rel, n, "L01", "unquoted value with YAML syntax; quote it")
        return val

    # -- skills ----------------------------------------------------------
    def check_hooks(self, prel: str, pdir: Path) -> None:
        """L19 for hook plugins: hooks/hooks.json parses, every command points at a script inside
        hooks/ that exists, and every Python hook script passes its offline --self-test."""
        hj = pdir / "hooks" / "hooks.json"
        if not hj.exists():
            self.err(prel, 0, "L19", "hook plugin without hooks/hooks.json")
            return
        try:
            cfg = json.loads(hj.read_text(encoding="utf-8"))
        except ValueError as e:
            self.err(self.rel(hj), 0, "L19", f"hooks.json is not valid JSON: {e}")
            return
        scripts = set()
        for groups in (cfg.get("hooks") or {}).values():
            for group in groups:
                for h in group.get("hooks", []):
                    cmd = h.get("command", "")
                    m = re.search(r"\$\{CLAUDE_PLUGIN_ROOT\}/(hooks/[\w./-]+)", cmd)
                    if not m:
                        self.err(self.rel(hj), 0, "L19", f"hook command does not run a script from hooks/: {cmd!r}")
                        continue
                    target = pdir / m.group(1)
                    if not target.is_file():
                        self.err(self.rel(hj), 0, "L19", f"hook script {m.group(1)} does not exist")
                    else:
                        scripts.add(target)
        if not scripts:
            self.err(self.rel(hj), 0, "L19", "hooks.json declares no hook commands")
        for script in sorted(scripts):
            if script.suffix != ".py":
                continue
            try:
                r = subprocess.run([sys.executable, "-I", str(script), "--self-test"], capture_output=True,
                                   text=True, timeout=120)
            except subprocess.TimeoutExpired:
                self.err(self.rel(script), 0, "L19", "hook --self-test timed out")
                continue
            if r.returncode != 0:
                tail = (r.stdout + r.stderr).strip().splitlines()[-1:] or ["no output"]
                self.err(self.rel(script), 0, "L19", f"hook --self-test failed: {tail[0]}")

    def check_skill(self, plugin: str, skill_dir: Path) -> None:
        skill_md = skill_dir / "SKILL.md"
        rel = self.rel(skill_md)
        if not skill_md.is_file():
            self.err(self.rel(skill_dir), 0, "L01", "skill directory without SKILL.md")
            return
        text = self.read_text(skill_md) or ""
        lines = text.splitlines()
        parsed, body_start = self.parse_frontmatter(skill_md, lines)
        if parsed is None:
            return
        data, order = parsed["data"], parsed["order"]
        line_of = {k: n for k, n in order}

        allowed = list(SPEC_KEYS) + ([] if plugin in PORTABLE_PLUGINS else CLAUDE_KEYS)
        for key, n in order:
            if key not in allowed:
                where = "core/saas skills take spec fields only" if plugin in PORTABLE_PLUGINS else "unknown field"
                self.err(rel, n, "L02", f"key '{key}' not allowed ({where})")
        if "allowed-tools" in data:
            self.warn(rel, line_of["allowed-tools"], "L02", "allowed-tools pre-approves tools; not used in wave 1")
        rank = {k: i for i, k in enumerate(SPEC_KEYS + CLAUDE_KEYS)}
        known = [(k, n) for k, n in order if k in rank]
        for (a, _), (b, nb) in zip(known, known[1:]):
            if rank[b] < rank[a]:
                self.err(rel, nb, "L02", f"key '{b}' must come before '{a}' (order: {', '.join(SPEC_KEYS)}, then Claude-only keys)")

        name = data.get("name")
        if not isinstance(name, str) or not name:
            self.err(rel, line_of.get("name", 1), "L03", "missing name")
        else:
            n = line_of["name"]
            if not NAME_RE.match(name) or len(name) > 64:
                self.err(rel, n, "L03", "name must match ^[a-z0-9]+(-[a-z0-9]+)*$ and be at most 64 characters")
            if name != skill_dir.name:
                self.err(rel, n, "L03", f"name '{name}' differs from directory '{skill_dir.name}'")
            if "claude" in name or "anthropic" in name:
                self.err(rel, n, "L03", "name contains a reserved word")
            if name in self.skill_names:
                self.err(rel, n, "L03", f"skill name '{name}' is used twice in this repository")
            self.skill_names.add(name)

        desc = data.get("description")
        dn = line_of.get("description", 1)
        if not isinstance(desc, str) or not desc.strip():
            self.err(rel, dn, "L04", "missing description")
        else:
            if len(desc) > 1024:
                self.err(rel, dn, "L04", f"description has {len(desc)} characters (max 1024)")
            # Claude Code lists description plus when_to_use for every skill within a
            # budget of 1% of the context window and drops the least-used entries first.
            when = data.get("when_to_use")
            listed = len(desc) + (len(when) if isinstance(when, str) else 0)
            if listed > LISTING_WARN:
                self.warn(rel, dn, "L21", f"skill listing text has {listed} characters (description plus "
                          f"when_to_use); aim for 400, at most {LISTING_WARN}")
            if "<" in desc or ">" in desc:
                self.err(rel, dn, "L04", "angle brackets in description; use [placeholder]")
            if "Use when" not in desc:
                self.warn(rel, dn, "L04", "description has no 'Use when' clause")
            if re.match(r"^(I|You|We)\b", desc):
                self.warn(rel, dn, "L04", "description should be written in the third person")
            raw = lines[dn - 1].split(":", 1)[1].strip() if dn - 1 < len(lines) else ""
            if not raw.startswith('"'):
                self.warn(rel, dn, "L04", "description should be one double-quoted line")

        lic = data.get("license")
        if lic is None:
            self.err(rel, 1, "L05", "missing license")
        elif lic != "Apache-2.0":
            self.err(rel, line_of["license"], "L05", "license must be Apache-2.0")
        meta = data.get("metadata")
        if meta is not None and not isinstance(meta, dict):
            self.err(rel, line_of["metadata"], "L01", "metadata must be a mapping of strings")
        elif isinstance(meta, dict) and "version" in meta:
            self.warn(rel, line_of["metadata"], "L02", "no version in skill metadata; the plugin carries it")
        paths = data.get("paths")
        if paths is not None and not (isinstance(paths, list) and paths):
            self.err(rel, line_of["paths"], "L02", "paths must be a non-empty block list")

        body = lines[body_start:]
        if len(body) > 500:
            self.err(rel, body_start + 501, "L07", f"body has {len(body)} lines (max 500)")
        elif len(body) > 300:
            self.warn(rel, body_start + 301, "L07", f"body has {len(body)} lines (target 300 or fewer)")

        self.check_skill_links(skill_dir, lines, body_start)
        self.check_rule_tags(rel, lines, body_start)

    def check_skill_links(self, skill_dir: Path, lines: list[str], body_start: int) -> None:
        rel = self.rel(skill_dir / "SKILL.md")
        linked: set[str] = set()
        in_code = False
        for i in range(body_start, len(lines)):
            line = lines[i]
            if line.lstrip().startswith("```"):
                in_code = not in_code
                continue
            if in_code:
                continue
            for m in LINK_RE.finditer(line):
                target = m.group(1).split("#", 1)[0]
                if not target or re.match(r"^[a-z][a-z0-9+.-]*:", target, re.I):
                    continue
                if target.startswith("/") or ".." in Path(target).parts or "\\" in target:
                    self.err(rel, i + 1, "L07", f"link '{target}' leaves the skill directory or is absolute")
                    continue
                norm = target[2:] if target.startswith("./") else target
                if not (skill_dir / norm).exists():
                    self.err(rel, i + 1, "L07", f"link target '{norm}' does not exist")
                top = norm.split("/", 1)[0]
                if "/" in norm and top not in {"references", "scripts", "assets"}:
                    self.err(rel, i + 1, "L07", f"link '{norm}' outside references/, scripts/ or assets/")
                if top == "references":
                    if norm.count("/") > 1:
                        self.err(rel, i + 1, "L07", "references are one level deep")
                    linked.add(norm)
        ref_dir = skill_dir / "references"
        if not ref_dir.is_dir():
            return
        for f in sorted(ref_dir.rglob("*")):
            if not f.is_file():
                continue
            r = f.relative_to(skill_dir).as_posix()
            if f.parent != ref_dir:
                self.err(self.rel(f), 0, "L07", "nested directory under references/ (one level only)")
            if r not in linked:
                self.err(self.rel(f), 0, "L07", "reference file is not linked from SKILL.md")
            text = self.read_text(f)
            if text is None:
                continue
            rlines = text.splitlines()
            if len(rlines) > 100 and not any(re.match(r"^##\s+Contents\s*$", l) for l in rlines[:40]):
                self.err(self.rel(f), 1, "L07", "reference over 100 lines needs a '## Contents' section at the top")
            in_code = False
            for j, line in enumerate(rlines):
                if line.lstrip().startswith("```"):
                    in_code = not in_code
                    continue
                if in_code:
                    continue
                for m in LINK_RE.finditer(line):
                    target = m.group(1).split("#", 1)[0]
                    if target and not re.match(r"^[a-z][a-z0-9+.-]*:", target, re.I):
                        self.err(self.rel(f), j + 1, "L07", f"reference links to another file ('{target}'); keep references one level deep")

    def check_rule_tags(self, rel: str, lines: list[str], body_start: int) -> None:
        body = lines[body_start:]
        has_sources = False
        for i, line in enumerate(body):
            if re.match(r"^##\s+Sources\s*$", line):
                block = "\n".join(body[i + 1:])
                block = re.split(r"^##\s", block, maxsplit=1, flags=re.M)[0]
                has_sources = "https://" in block
        if not has_sources:
            self.warn(rel, body_start + 1, "L08", "no '## Sources' section with an https:// URL")

        # A rule block starts at a bullet or heading tagged [invariant]/[default]
        # and runs until the next bullet at the same level or the next heading.
        starts = []
        for i, line in enumerate(body):
            m = re.match(r"^(\s*-\s+|#{2,4}\s+(?:\d+\.\s+)?)\[(invariant|default)\]", line)
            if m:
                starts.append((i, m.group(2), line.startswith("#")))
        for idx, (i, tag, heading) in enumerate(starts):
            j = i + 1
            while j < len(body):
                nxt = body[j]
                if heading and re.match(r"^#{1,4}\s", nxt):
                    break
                if not heading and (re.match(r"^\s*-\s+", nxt) or re.match(r"^#{1,4}\s", nxt) or not nxt.strip()):
                    break
                j += 1
            block = "\n".join(body[i:j])
            n = body_start + i + 1
            if tag == "invariant" and "Test:" not in block:
                self.warn(rel, n, "L08", "[invariant] rule without a 'Test:' recipe")
            if tag == "default" and ("Trade-off:" not in block or "ADR" not in block):
                self.warn(rel, n, "L08", "[default] rule needs 'Trade-off:' and the ADR clause")
            if "Source:" not in block and "Proof:" not in block and "Test:" not in block:
                self.warn(rel, n, "L08", "rule without a 'Source:' line")

    # -- evals -----------------------------------------------------------
    def frontmatter_tags(self, text: str) -> list[str] | None:
        lines = text.splitlines()
        if not lines or lines[0].strip() != "---":
            return None
        tags: list[str] | None = None
        for i in range(1, len(lines)):
            line = lines[i]
            if line.strip() == "---":
                break
            m = re.match(r"^tags:\s*(.*)$", line)
            if m:
                val = m.group(1).strip()
                if val.startswith("["):
                    tags = [t.strip().strip("\"'") for t in val.strip("[]").split(",") if t.strip()]
                else:
                    tags = []
                    for nxt in lines[i + 1:]:
                        mm = re.match(r"^\s+-\s+(.*)$", nxt)
                        if not mm:
                            break
                        tags.append(mm.group(1).strip().strip("\"'"))
        return tags

    def check_evals(self, plugin_dir: Path, skills: set[str]) -> None:
        evals = plugin_dir / "evals"
        plugin = plugin_dir.name
        if not evals.is_dir():
            if skills:
                self.warn(self.rel(plugin_dir), 0, "L20", "plugin has skills but no evals/ directory")
            return
        covered: dict[str, set[str]] = {}
        for group in sorted(p for p in evals.iterdir() if p.is_dir()):
            if group.name == "results":
                continue
            grel = self.rel(group)
            if (group / "prompt.md").exists() or (group / "case.yaml").exists():
                self.err(grel, 0, "L20", "case directly under evals/; group cases by skill name")
                continue
            if group.name not in skills:
                self.err(grel, 0, "L20", f"eval group '{group.name}' matches no skill in plugin '{plugin}'")
            for case in sorted(p for p in group.iterdir() if p.is_dir()):
                crel = self.rel(case)
                prompt = case / "prompt.md"
                caseyaml = case / "case.yaml"
                if not prompt.exists() and not caseyaml.exists():
                    self.err(crel, 0, "L20", "case has neither prompt.md nor case.yaml")
                    continue
                if not re.match(r"^[A-Za-z0-9][A-Za-z0-9._-]*$", case.name):
                    self.err(crel, 0, "L20", "case name must start with a letter or digit and use letters, digits, . _ -")
                graders = sorted((case / "graders").glob("*.md")) if (case / "graders").is_dir() else []
                yaml_text = self.read_text(caseyaml) or "" if caseyaml.exists() else ""
                if not graders and not re.search(r"^graders:", yaml_text, re.M):
                    self.err(crel, 0, "L20", "case has no grader")
                tags = self.frontmatter_tags(self.read_text(prompt) or "") if prompt.exists() else None
                if tags is None:
                    m = re.search(r"^tags:\s*(.*)$", yaml_text, re.M)
                    tags = self.frontmatter_tags("---\n" + m.group(0) + "\n---") if m else []
                kinds = EVAL_KINDS.intersection(tags or [])
                if group.name not in (tags or []):
                    self.err(crel, 0, "L20", f"tags must include the skill name '{group.name}'")
                if len(kinds) != 1:
                    self.err(crel, 0, "L20", "tags must include exactly one of trigger, near-miss, output, adversarial")
                covered.setdefault(group.name, set()).update(kinds)
                for g in graders:
                    gt = self.read_text(g) or ""
                    if re.search(r"^tool:\s*['\"]?Skill['\"]?\s*$", gt, re.M):
                        m = re.search(r"^input_match:\s*(.+)$", gt, re.M)
                        if not m or not any(s in m.group(1) for s in self.skill_names):
                            self.err(self.rel(g), 0, "L20", "Skill grader input_match names no existing skill")
        for s in sorted(skills):
            if s not in covered:
                self.warn(self.rel(evals), 0, "L20", f"skill '{s}' has no eval cases")
            elif plugin == "core" and "adversarial" not in covered[s]:
                self.warn(self.rel(evals / s), 0, "L20", f"core skill '{s}' has no adversarial case")

    # -- manifests -------------------------------------------------------
    def load_json(self, path: Path):
        try:
            return json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as e:
            self.err(self.rel(path), 1, "L18", f"cannot parse JSON: {e}")
            return None

    def check_repo(self) -> None:
        lic = self.root / "LICENSE"
        lt = self.read_text(lic) if lic.exists() else None
        if not lt or "Apache License" not in lt or "Version 2.0" not in lt:
            self.err("LICENSE", 0, "L05", "root LICENSE must be the Apache License 2.0 text")
        if not (self.root / "NOTICE").is_file():
            self.err("NOTICE", 0, "L05", "NOTICE file missing")

        mp_path = self.root / ".claude-plugin" / "marketplace.json"
        if not mp_path.is_file():
            self.err(".claude-plugin/marketplace.json", 0, "L18", "marketplace.json missing")
            return
        mp = self.load_json(mp_path)
        if mp is None:
            return
        mrel = self.rel(mp_path)
        allow_x = set(mp.get("allowCrossMarketplaceDependenciesOn") or [])
        entries = mp.get("plugins") or []
        names = []
        total_skills = 0
        for entry in entries:
            ename = entry.get("name", "")
            names.append(ename)
            if "version" in entry:
                self.err(mrel, 0, "L18", f"entry '{ename}' sets version; keep it only in plugin.json")
            for key in ("skills", "hooks", "mcpServers", "commands", "agents"):
                if key in entry:
                    self.err(mrel, 0, "L18", f"entry '{ename}' declares '{key}'; components belong in the plugin")
            src = entry.get("source")
            if not isinstance(src, str) or not src.startswith("./") or ".." in src:
                self.err(mrel, 0, "L18", f"entry '{ename}' needs a relative source starting with ./")
                continue
            pdir = (self.root / src).resolve()
            pj_path = pdir / ".claude-plugin" / "plugin.json"
            if not pj_path.is_file():
                self.err(mrel, 0, "L18", f"entry '{ename}' points to {src}, which has no .claude-plugin/plugin.json")
                continue
            pj = self.load_json(pj_path)
            if pj is None:
                continue
            prel = self.rel(pj_path)
            if pj.get("name") != ename:
                self.err(prel, 0, "L18", f"plugin.json name '{pj.get('name')}' differs from marketplace entry '{ename}'")
            ver = pj.get("version", "")
            if not SEMVER_RE.match(str(ver)):
                self.err(prel, 0, "L18", "plugin.json version must be semver")
            if pj.get("license") != "Apache-2.0":
                self.err(prel, 0, "L05", "plugin.json license must be Apache-2.0")
            for key in ("hooks", "mcpServers", "lspServers"):
                if key in pj and not (key == "hooks" and ename in HOOK_PLUGINS):
                    self.err(prel, 0, "L19", f"plugin.json declares '{key}'; wave 1 ships skills only")
            for dep in pj.get("dependencies") or []:
                mk = None
                if isinstance(dep, dict):
                    mk = dep.get("marketplace")
                elif isinstance(dep, str) and "@" in dep:
                    mk = dep.split("@", 1)[1]
                if mk and mk != MARKETPLACE and mk not in allow_x:
                    self.err(prel, 0, "L18", f"dependency on marketplace '{mk}' not in allowCrossMarketplaceDependenciesOn")
            ch = pdir / "CHANGELOG.md"
            ct = self.read_text(ch) if ch.exists() else None
            if not ct or not re.search(r"^##\s+\[?" + re.escape(str(ver)) + r"\]?(\s|$)", ct, re.M):
                self.err(self.rel(ch), 0, "L18", f"CHANGELOG.md has no heading for version {ver}")
            rd = pdir / "README.md"
            rt = self.read_text(rd) if rd.exists() else None
            if not rt or not re.search(r"(?:/|claude )plugin install " + re.escape(f"{ename}@{MARKETPLACE}"), rt):
                self.err(self.rel(rd), 0, "L18", f"README.md lacks the install line 'plugin install {ename}@{MARKETPLACE}'")
            for bad in ("bin", "hooks"):
                if bad == "hooks" and ename in HOOK_PLUGINS:
                    self.check_hooks(prel, pdir)
                    continue
                if (pdir / bad).exists():
                    self.err(self.rel(pdir / bad), 0, "L19", f"{bad}/ is not allowed in wave-1 plugins")
            if (pdir / ".mcp.json").exists():
                self.err(self.rel(pdir / ".mcp.json"), 0, "L19", ".mcp.json is not allowed in wave-1 plugins")
            if (pdir / "CLAUDE.md").exists():
                self.err(self.rel(pdir / "CLAUDE.md"), 0, "L19", "CLAUDE.md inside a plugin is not loaded")

            skills_dir = pdir / "skills"
            skill_dirs = sorted(p for p in skills_dir.iterdir() if p.is_dir()) if skills_dir.is_dir() else []
            if ename in NO_SKILL_PLUGINS:
                if skill_dirs:
                    self.err(self.rel(skills_dir), 0, "L00", f"'{ename}' ships no skills")
            elif not skill_dirs:
                self.warn(self.rel(pdir), 0, "L00", "plugin has no skills yet")
            for sd in skill_dirs:
                self.check_skill(ename, sd)
            total_skills += len(skill_dirs)
        if len(set(names)) != len(names):
            self.err(mrel, 0, "L18", "duplicate plugin names in marketplace.json")
        plugins_root = self.root / "plugins"
        if plugins_root.is_dir():
            listed = {Path(e.get("source", "")).name for e in entries}
            for p in sorted(plugins_root.iterdir()):
                if p.is_dir() and p.name not in listed:
                    self.warn(self.rel(p), 0, "L18", "plugin directory not listed in marketplace.json")
        if total_skills == 0:
            self.warn(mrel, 0, "L00", "no skills found; skill checks did not run")
        # Evals after all skills are known, so Skill graders can be checked.
        for entry in entries:
            src = entry.get("source")
            if isinstance(src, str) and src.startswith("./"):
                pdir = (self.root / src).resolve()
                sd = pdir / "skills"
                names_here = {p.name for p in sd.iterdir() if p.is_dir()} if sd.is_dir() else set()
                if entry.get("name") not in NO_SKILL_PLUGINS:
                    self.check_evals(pdir, names_here)

    # -- commits ---------------------------------------------------------
    def check_commits(self, rng: str) -> None:
        try:
            out = subprocess.run(
                ["git", "-C", str(self.root), "log", "--format=%H%x00%B%x01", rng],
                capture_output=True, check=True,
            ).stdout.decode("utf-8", "replace")
        except (OSError, subprocess.CalledProcessError) as e:
            self.err("git", 0, "L17", f"cannot read commit range '{rng}': {e}")
            return
        for chunk in out.split("\x01"):
            if "\x00" not in chunk:
                continue
            sha, msg = chunk.strip().split("\x00", 1)
            for rx in ATTRIB_HARD_RES + [ATTRIB_SOFT_RE, re.compile(r"https://claude\.ai/(?:code|chat)/", re.I)]:
                if rx.search(msg):
                    self.err(f"commit {sha[:12]}", 0, "L17", "commit message carries an attribution trailer, footer or session link")
                    break

    # -- run -------------------------------------------------------------
    def denylist(self) -> tuple[list[str], bool]:
        terms: list[str] = []
        found = False
        f = self.root / ".denylist.local"
        if f.is_file():
            found = True
            terms += f.read_text(encoding="utf-8").splitlines()
        env = os.environ.get("SKILLS_DENYLIST")
        if env:
            found = True
            terms += re.split(r"[\n,]", env)
        clean = []
        for t in terms:
            t = t.strip()
            if t and not t.startswith("#") and t.lower() not in {c.lower() for c in clean}:
                clean.append(t)
        return clean, found

    def run(self, commits: str | None) -> int:
        terms, found = self.denylist()
        if not found:
            self.warn(".denylist.local", 0, "L14", "no private term list (.denylist.local or SKILLS_DENYLIST); term check skipped")
        for path in self.files():
            text = self.read_text(path)
            if text is not None:
                self.check_content(path, text, terms)
        self.check_repo()
        if commits:
            self.check_commits(commits)
        return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="lint.py",
        description="Lint the skills marketplace: skill frontmatter and layout, manifests, evals and public-safety rules.",
        epilog="Private terms come from .denylist.local (one per line) and the SKILLS_DENYLIST environment variable "
        "(newline or comma separated). Hits print the term's index, never the term.",
    )
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent,
                    help="repository root to lint (default: the parent of tools/)")
    ap.add_argument("--commits", metavar="RANGE",
                    help="also check commit messages in a git range, for example origin/main..HEAD")
    ap.add_argument("--strict", action="store_true", help="treat warnings as errors")
    ap.add_argument("-q", "--quiet", action="store_true", help="print errors only")
    args = ap.parse_args(argv)

    root = args.root.resolve()
    if not root.is_dir():
        print(f"lint.py: {root} is not a directory", file=sys.stderr)
        return 2
    linter = Linter(root, args.strict)
    linter.run(args.commits)

    order = {"error": 0, "warning": 1}
    linter.findings.sort(key=lambda f: (order[f.level], f.path, f.line, f.rule))
    errors = sum(1 for f in linter.findings if f.level == "error")
    warnings = len(linter.findings) - errors
    for f in linter.findings:
        if args.quiet and f.level != "error":
            continue
        print(f"{f.path}:{f.line}: {f.level} {f.rule} {f.message}")
    sys.stdout.flush()
    print(f"{errors} error(s), {warnings} warning(s), {len(linter.skill_names)} skill(s) checked", file=sys.stderr)
    if errors or (args.strict and warnings):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
